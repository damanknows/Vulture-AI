"""
Reproducible Explanation-Quality Evaluation (25 Records, Dual-Judge)
====================================================================

1. Generates 25 explanations via `vulture_chatbot.chat_with_validation` on the
   first 25 real CVEs from `data/benchmark/cves.csv` (deterministic stub LLM,
   plus live `qwen-3.8-27b` via Cerebras when `CEREBRAS_API_KEY` is configured).
2. Evaluates the 25 live explanations using two independent judge models
   (`qwen-3.8-27b` and `gpt-oss-120b`) at temperature=0.0, seed=20261127,
   on a 1-5 rubric:
   - factual_consistency
   - evidence_grounding
   - actionability
   - clarity
3. Computes mean/SD per judge and quadratic-weighted Cohen's kappa between judges.
4. Logs exact judge prompt, prompt SHA-256, and raw judge outputs.

Usage:
    python3 -m experiments.revision.explanation.llm_judge
"""

import csv
import hashlib
import json
import os
import re
import time
import urllib.error
import urllib.request
from pathlib import Path
from types import SimpleNamespace
from typing import Callable, Dict, List, Optional, Tuple

import numpy as np

import vulture_chatbot
from experiments.run_baselines import load_benchmark


BENCHMARK_CSV = Path("data/benchmark/cves.csv")
OUT_DIR = Path("experiments/revision/explanation")
OUT_CSV = OUT_DIR / "explanation_evaluation.csv"
OUT_SUMMARY = OUT_DIR / "explanation_summary.json"
OUT_RAW = OUT_DIR / "judge_raw_logs.jsonl"

SEED = 20261127
N_RECORDS = 25
CEREBRAS_URL = "https://api.cerebras.ai/v1/chat/completions"
GENERATOR_MODEL = "qwen-3.8-27b"
JUDGE_MODELS = ("qwen-3.8-27b", "gpt-oss-120b")
RUBRIC_DIMS = ("factual_consistency", "evidence_grounding", "actionability", "clarity")

JUDGE_SYSTEM_PROMPT = (
    "You are a strict cybersecurity evaluation judge. "
    "Evaluate the assistant's JSON vulnerability explanation ONLY against the provided retrieved evidence. "
    "Score each criterion as an integer from 1 (poor) to 5 (excellent):\n"
    "1. factual_consistency: Are all stated CVE IDs, CVSS, EPSS, and KEV facts consistent with the evidence?\n"
    "2. evidence_grounding: Does the explanation avoid unsupported claims beyond the evidence?\n"
    "3. actionability: Is the recommended remediation concrete and useful for a SOC analyst?\n"
    "4. clarity: Is the explanation clear, concise, and well-structured?\n"
    "Return STRICT JSON ONLY with keys: "
    "{\"factual_consistency\": int, \"evidence_grounding\": int, \"actionability\": int, \"clarity\": int, \"notes\": str}."
)
JUDGE_PROMPT_SHA256 = hashlib.sha256(JUDGE_SYSTEM_PROMPT.encode("utf-8")).hexdigest()


def _load_env_key(key_name: str = "CEREBRAS_API_KEY") -> Optional[str]:
    val = os.getenv(key_name)
    if val:
        return val.strip()
    env_path = Path(".env")
    if env_path.exists():
        for line in env_path.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if line and not line.startswith("#") and "=" in line:
                k, v = line.split("=", 1)
                if k.strip() == key_name:
                    return v.strip().strip('"').strip("'")
    return None


def _cerebras_completion(
    model: str,
    messages: List[dict],
    temperature: float = 0.0,
    seed: int = SEED,
    api_key: Optional[str] = None,
) -> SimpleNamespace:
    key = api_key or _load_env_key("CEREBRAS_API_KEY")
    if not key:
        raise RuntimeError("CEREBRAS_API_KEY not configured")
    payload = {
        "model": model,
        "messages": messages,
        "temperature": temperature,
        "seed": seed,
        "max_tokens": 600,
    }
    req = urllib.request.Request(
        CEREBRAS_URL,
        data=json.dumps(payload).encode("utf-8"),
        headers={
            "Authorization": f"Bearer {key}",
            "Content-Type": "application/json",
            "User-Agent": "Vulture-AI/1.0",
        },
        method="POST",
    )
    with urllib.request.urlopen(req, timeout=30) as resp:
        data = json.loads(resp.read().decode("utf-8"))
    content = data["choices"][0]["message"]["content"]
    return SimpleNamespace(choices=[SimpleNamespace(message=SimpleNamespace(content=content))])


def _stub_completion(messages: List[dict], **_kwargs) -> SimpleNamespace:
    user_msg = messages[-1]["content"]
    m_cve = re.search(r"CVE-\d{4}-\d+", user_msg)
    cid = m_cve.group(0) if m_cve else "CVE-UNKNOWN"
    obj = {
        "cve_id": cid,
        "cvss_severity": "HIGH",
        "priority": "high",
        "explanation": f"Deterministic stub summary grounded in retrieved evidence for {cid}.",
        "evidence_references": [f"benchmark_host:443_{cid}"],
        "uncertainties": ["Generated by deterministic stub LLM."],
        "recommended_remediation": f"Verify applicability of {cid} on benchmark_host and apply vendor patch.",
    }
    return SimpleNamespace(choices=[SimpleNamespace(message=SimpleNamespace(content=json.dumps(obj)))])


def _build_dataset_for_findings(findings: List[dict]) -> List[dict]:
    out = []
    for f in findings:
        m = dict(f["cve_matches"][0])
        m["retrieved_at"] = "2026-10-14T00:00:00Z"
        out.append({"finding": f["finding"], "cve_matches": [m]})
    return out


def _parse_judge_json(raw_text: str) -> Dict[str, object]:
    text = raw_text.strip()
    if text.startswith("```json"):
        text = text[7:]
    elif text.startswith("```"):
        text = text[3:]
    if text.endswith("```"):
        text = text[:-3]
    # Extract first JSON object if surrounded by text
    m = re.search(r"\{.*\}", text.strip(), re.DOTALL)
    if not m:
        raise ValueError(f"No JSON object in judge output: {raw_text[:120]}")
    obj = json.loads(m.group(0))
    for dim in RUBRIC_DIMS:
        val = int(obj[dim])
        if not (1 <= val <= 5):
            raise ValueError(f"Score {dim}={val} out of [1, 5]")
        obj[dim] = val
    return obj


def quadratic_weighted_kappa(y1: List[int], y2: List[int], min_rating: int = 1, max_rating: int = 5) -> float:
    """Computes quadratic-weighted Cohen's kappa for ordinal 1-5 ratings."""
    if len(y1) != len(y2) or not y1:
        return 0.0
    n_cat = max_rating - min_rating + 1
    conf = np.zeros((n_cat, n_cat), dtype=float)
    for a, b in zip(y1, y2):
        conf[a - min_rating, b - min_rating] += 1.0
    n = float(len(y1))
    hist1 = conf.sum(axis=1)
    hist2 = conf.sum(axis=0)
    expected = np.outer(hist1, hist2) / n
    w = np.zeros((n_cat, n_cat), dtype=float)
    for i in range(n_cat):
        for j in range(n_cat):
            w[i, j] = ((i - j) ** 2) / ((n_cat - 1) ** 2)
    denom = float(np.sum(w * expected))
    if denom == 0.0:
        return 1.0 if np.array_equal(y1, y2) else 0.0
    return round(1.0 - float(np.sum(w * conf)) / denom, 4)


def run_explanation_evaluation(
    benchmark_path: Path = BENCHMARK_CSV,
    out_csv: Path = OUT_CSV,
    out_summary: Path = OUT_SUMMARY,
    out_raw: Path = OUT_RAW,
    n_records: int = N_RECORDS,
    seed: int = SEED,
    completion_fn: Optional[Callable] = None,
    judge_models: Tuple[str, ...] = JUDGE_MODELS,
) -> Dict[str, object]:
    findings, _, _ = load_benchmark(str(benchmark_path))
    real_findings = [f for f in findings if not f["cve_matches"][0]["cve_id"].startswith("CVE-2024-9999")][:n_records]
    dataset = _build_dataset_for_findings(real_findings)

    api_key = _load_env_key("CEREBRAS_API_KEY")
    if completion_fn is None and not api_key:
        out_csv.parent.mkdir(parents=True, exist_ok=True)
        out_csv.write_text("status,reason\nNOT_AVAILABLE,No live LLM API key configured\n", encoding="utf-8")
        summary = {"status": "NOT_AVAILABLE", "reason": "CEREBRAS_API_KEY not configured"}
        out_summary.write_text(json.dumps(summary, indent=2), encoding="utf-8")
        return summary

    call_fn = completion_fn or (lambda model, messages, temperature=0.0, **kw: _cerebras_completion(model, messages, temperature=temperature, seed=seed, api_key=api_key))

    orig_completion = vulture_chatbot.completion
    rows = []
    raw_logs = []

    try:
        # 1. Generate 25 stub explanations (for deterministic baseline check) + 25 live explanations
        stub_valid_count = 0
        vulture_chatbot.completion = lambda model, messages, temperature=0.0, **kw: _stub_completion(messages)
        for f in real_findings:
            cid = f["cve_matches"][0]["cve_id"]
            res_stub = vulture_chatbot.chat_with_validation(
                query=f"Explain {cid}",
                dataset=dataset,
                cve_id=cid,
                finding=f,
                model="stub",
                config_mode="D",
            )
            if res_stub.get("validation_status") == "passed":
                stub_valid_count += 1

        # 2. Generate live explanations via chat_with_validation and score with dual judges
        vulture_chatbot.completion = call_fn
        live_valid_count = 0
        try:
            for f in real_findings:
                cid = f["cve_matches"][0]["cve_id"]
                ev_record = [d["cve_matches"][0] for d in dataset if d["cve_matches"][0]["cve_id"] == cid][0]
                res_live = vulture_chatbot.chat_with_validation(
                    query=f"Explain {cid} and recommend remediation.",
                    dataset=dataset,
                    cve_id=cid,
                    finding=f,
                    model=GENERATOR_MODEL,
                    config_mode="D",
                )
                if res_live.get("validation_status") == "passed":
                    live_valid_count += 1

                for j_model in judge_models:
                    judge_user = (
                        f"Target CVE: {cid}\n"
                        f"Retrieved Evidence: {json.dumps(ev_record)}\n"
                        f"Assistant Output: {json.dumps(res_live)}"
                    )
                    j_msgs = [
                        {"role": "system", "content": JUDGE_SYSTEM_PROMPT},
                        {"role": "user", "content": judge_user},
                    ]
                    j_resp = call_fn(model=j_model, messages=j_msgs, temperature=0.0)
                    j_raw = j_resp.choices[0].message.content
                    parsed = _parse_judge_json(j_raw)
                    rows.append(
                        {
                            "cve_id": cid,
                            "generator_model": GENERATOR_MODEL,
                            "judge_model": j_model,
                            "seed": seed,
                            "judge_prompt_sha256": JUDGE_PROMPT_SHA256,
                            "validation_status": res_live.get("validation_status", ""),
                            "factual_consistency": parsed["factual_consistency"],
                            "evidence_grounding": parsed["evidence_grounding"],
                            "actionability": parsed["actionability"],
                            "clarity": parsed["clarity"],
                        }
                    )
                    raw_logs.append(
                        {
                            "cve_id": cid,
                            "judge_model": j_model,
                            "seed": seed,
                            "judge_prompt_sha256": JUDGE_PROMPT_SHA256,
                            "assistant_output": res_live,
                            "raw_judge_output": j_raw,
                        }
                    )
                    if completion_fn is None:
                        time.sleep(0.2)
        except (urllib.error.HTTPError, urllib.error.URLError, RuntimeError, OSError) as exc:
            out_csv.parent.mkdir(parents=True, exist_ok=True)
            reason = f"Live LLM judge unavailable ({type(exc).__name__}: {exc})"
            with open(out_csv, "w", newline="", encoding="utf-8") as f:
                writer = csv.DictWriter(
                    f,
                    fieldnames=["status", "seed", "judge_prompt_sha256", "stub_validation_passed", "reason"],
                )
                writer.writeheader()
                writer.writerow(
                    {
                        "status": "NOT_AVAILABLE",
                        "seed": seed,
                        "judge_prompt_sha256": JUDGE_PROMPT_SHA256,
                        "stub_validation_passed": stub_valid_count,
                        "reason": reason,
                    }
                )
            summary = {
                "status": "NOT_AVAILABLE",
                "n_records": len(real_findings),
                "stub_validation_passed": stub_valid_count,
                "seed": seed,
                "judge_prompt_sha256": JUDGE_PROMPT_SHA256,
                "reason": reason,
                "human_spot_check": "PENDING (see docs/annotation/explanation_protocol.md)",
            }
            with open(out_summary, "w", encoding="utf-8") as f:
                json.dump(summary, f, indent=2)
            return summary
    finally:
        vulture_chatbot.completion = orig_completion

    out_csv.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = [
        "cve_id",
        "generator_model",
        "judge_model",
        "seed",
        "judge_prompt_sha256",
        "validation_status",
        "factual_consistency",
        "evidence_grounding",
        "actionability",
        "clarity",
    ]
    with open(out_csv, "w", newline="", encoding="utf-8") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)

    with open(out_raw, "w", encoding="utf-8") as f:
        for item in raw_logs:
            f.write(json.dumps(item) + "\n")

    # Compute aggregates per judge + inter-judge kappa
    per_judge: Dict[str, dict] = {}
    for j_model in judge_models:
        j_rows = [r for r in rows if r["judge_model"] == j_model]
        per_judge[j_model] = {}
        for dim in RUBRIC_DIMS:
            vals = [r[dim] for r in j_rows]
            per_judge[j_model][dim] = {
                "mean": round(float(np.mean(vals)), 4),
                "sd": round(float(np.std(vals, ddof=1)), 4) if len(vals) > 1 else 0.0,
            }

    inter_judge_kappa: Dict[str, float] = {}
    if len(judge_models) >= 2:
        j1, j2 = judge_models[0], judge_models[1]
        r1_map = {r["cve_id"]: r for r in rows if r["judge_model"] == j1}
        r2_map = {r["cve_id"]: r for r in rows if r["judge_model"] == j2}
        common = sorted(set(r1_map).intersection(r2_map))
        for dim in RUBRIC_DIMS:
            y1 = [r1_map[c][dim] for c in common]
            y2 = [r2_map[c][dim] for c in common]
            inter_judge_kappa[dim] = quadratic_weighted_kappa(y1, y2)

    summary = {
        "status": "COMPLETED",
        "n_records": len(real_findings),
        "n_judge_rows": len(rows),
        "generator_model": GENERATOR_MODEL,
        "judge_models": list(judge_models),
        "seed": seed,
        "temperature": 0.0,
        "judge_prompt_sha256": JUDGE_PROMPT_SHA256,
        "stub_validation_passed": stub_valid_count,
        "live_validation_passed": live_valid_count,
        "per_judge_stats": per_judge,
        "inter_judge_weighted_kappa": inter_judge_kappa,
        "human_spot_check": "PENDING (see docs/annotation/explanation_protocol.md)",
        "limitation": "Automated LLM-judge ratings are not a substitute for human SOC-analyst validation.",
    }
    with open(out_summary, "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2)

    return summary


if __name__ == "__main__":
    rep = run_explanation_evaluation()
    print(json.dumps(rep, indent=2))
